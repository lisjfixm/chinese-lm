# 對話擴充：用一致的角色／場所／物品組合生成「問—答」，讓「—」之後的轉移有足夠樣本
VERBS = ["吃飯", "出門", "回家", "看書", "寫作業", "上班", "上課", "睡覺",
         "運動", "休息", "買菜", "打掃", "洗澡", "開會", "加班", "起床",
         "喝茶", "看電視", "散步", "複習"]
OBJS = ["手機", "書包", "這件外套", "腳踏車", "這本書", "那雙鞋", "杯子", "椅子"]
PRICES = ["一百二十", "三百五十", "五百", "八十", "兩千"]
PLACES2 = ["車站", "市場", "學校", "公園", "醫院", "捷運站", "超市"]


def build_dialog(rng: random.Random, target: int) -> list[str]:
    out: list[str] = []
    tries = 0
    while len(out) < target and tries < target * 30:
        tries += 1
        v = rng.choice(VERBS)
        v2 = rng.choice(VERBS)
        t = rng.choice(TIMES)
        t2 = rng.choice(TIMES)
        o = rng.choice(OBJS)
        pz = rng.choice(PRICES)
        pl = rng.choice(PLACES2)
        k = rng.randint(0, 8)
        if k == 0:
            q, a = f"{t}你{v}了嗎？", f"—我{v}了，你呢？"
        elif k == 1:
            q, a = f"要不要一起{v}？", f"—好啊，{t2}一起去。"
        elif k == 2:
            q, a = f"你怎麼去{pl}？", "—我搭公車，大概二十分鐘。"
        elif k == 3:
            q, a = f"{pl}在哪裡？", "—在前面那個路口，走五分鐘就到。"
        elif k == 4:
            q, a = f"這個{o}多少錢？", f"—一共{pz}元。"
        elif k == 5:
            q, a = f"你覺得這個{o}怎麼樣？", "—我覺得還不錯，用起來很順。"
        elif k == 6:
            q, a = f"明天要不要去{pl}？", f"—可以，{t2}出發。"
        elif k == 7:
            q, a = f"你喜歡{v}嗎？", f"—喜歡，尤其是{t2}的時候。"
        else:
            q, a = f"{t}有沒有{v}？", f"—有，{v2}完就去。"
        out.append(q + a)
    return out


def build_scene_sentences(rng: random.Random, per_action: int) -> list[str]:
    """從動作三元組展開句子；地點與人物都跟著動作走，不會亂配。"""
    out: list[str] = []
    weights = [1.0, 1.0, 1.0, 1.0, 0.35, 0.6, 0.3, 0.6, 0.5, 0.5]
    kinds = list(range(len(weights)))
    for act, places, agents in ACTIONS:
        pool = []
        for _ in range(per_action * 20):
            t = rng.choice(TIMES)
            p = rng.choice(places)
            a = rng.choice(agents)
            ap = rng.choice(ADJ_PERSON)
            apl = rng.choice(ADJ_PLACE)
            k = rng.choices(kinds, weights=weights, k=1)[0]
            if k == 0:
                sent = f"{t}，{a}在{p}{act}。"
            elif k == 1:
                sent = f"{t}的{p}很{apl}，{a}正在{act}。"
            elif k == 2:
                sent = f"{a}在{p}{act}，看起來很{ap}。"
            elif k == 3:
                loc = p if p[-1] in "旁上前下" else p + "裡"
                sent = f"{loc}，{a}{act}，看起來很{ap}。"
            elif k == 4:
                sent = f"{t}我路過{p}，看見{a}在{act}。"
            elif k == 5:
                sent = f"{a}{act}的時候，{p}顯得很{apl}。"
            elif k == 6:
                sent = f"後來{a}去{p}{act}。"
            elif k == 7:
                sent = f"{t}，{p}的{a}正在{act}。"
            elif k == 8:
                sent = f"{a}說，等一下還要去{p}{act}。"
            else:
                sent = f"{t}的{p}很{apl}，{a}打算{act}。"
            pool.append(sent)
        uniq = list(dict.fromkeys(pool))
        rng.shuffle(uniq)
        out.extend(uniq[:per_action])
    return out


def main() -> None:
    with open(BASE, encoding="utf-8") as f:
        base = [line.strip() for line in f if line.strip()]

    rng = random.Random(2026)
    hand = list(base) + list(EXTRA)
    # 問句與答句寫在同一行：「問？—答。」這樣「？」→「—」→答句開頭的轉移
    # 才會出現在語料裡，聊天模式接得下去。
    dialog_lines: list[str] = []
    for q, a in DIALOG:
        dialog_lines.append(q + a)
    dialog_lines += build_dialog(rng, 1200)

    fixed = len(hand) + len(dialog_lines)
    need = max(TARGET - fixed, 0)
    per_action = math.ceil(need / len(ACTIONS)) + 10

    pool = hand + dialog_lines + build_scene_sentences(rng, per_action)

    seen: set[str] = set()
    sentences: list[str] = []
    for s in pool:
        if s not in seen:
            seen.add(s)
            sentences.append(s)

    if len(sentences) > TARGET:
        sentences = sentences[:TARGET]
    if len(sentences) < TARGET:
        raise SystemExit(f"候選句不足：僅 {len(sentences)}，請增加動作或模板")

    with open(CORPUS, "w", encoding="utf-8") as f:
        f.write("\n".join(sentences) + "\n")
    print(f"完成：{len(sentences)} 句（手寫 {fixed} 句，其中對話 {len(DIALOG)} 組；組合 {len(sentences) - fixed} 句）")


if __name__ == "__main__":
    main()
